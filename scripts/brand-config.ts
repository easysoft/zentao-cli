import { readFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve, relative, isAbsolute, posix } from 'node:path';
import { formatBrandText, type ResolvedBrand } from '../src/brand.js';

export function option(args: string[], name: string): string | undefined {
    const index = args.lastIndexOf(name);
    const value = index < 0 ? args.filter(arg => arg.startsWith(name + '=')).at(-1)?.slice(name.length + 1) : args[index + 1];
    if (value?.startsWith('--') || ((index >= 0) && !value)) throw new Error(`Missing value: ${name}`);
    return value;
}

export function loadBrand(file?: string): ResolvedBrand | undefined {
    if (!file) return undefined;
    const config = JSON.parse(readFileSync(file, 'utf8')) as ResolvedBrand;
    for (const key of ['displayName', 'commandName', 'packageName', 'homepage'] as const) {
        if (typeof config[key] !== 'string' || !config[key] || /[<>"'`\r\n\u0000]/.test(config[key])) throw new Error(`Invalid brand ${key}`);
    }
    if (!/^[\p{L}\p{N} _.()-]+$/u.test(config.displayName)) throw new Error('Invalid brand displayName');
    if (!/^[a-z][a-z0-9-]*$/.test(config.commandName) || !/^[a-z][a-z0-9-]*$/.test(config.packageName)) throw new Error('Brand command and package must be unscoped lowercase names');
    for (const url of [config.homepage, config.repository].filter(Boolean) as string[]) {
        const parsed = new URL(url);
        if (!['https:', 'http:'].includes(parsed.protocol) || parsed.username || parsed.password) throw new Error('Invalid public brand URL');
    }
    if (config.repository !== null && typeof config.repository !== 'string') throw new Error('Brand repository must be a public URL or null');
    if (config.logo) {
        const svg = readFileSync(resolve(dirname(resolve(file)), config.logo), 'utf8');
        if (!/<svg\b/.test(svg) || /<script\b|\bon\w+\s*=|(?:href|src)\s*=\s*["'](?!#)/i.test(svg)) throw new Error('Logo must be a self-contained SVG without scripts');
        config.logoSvg = svg.slice(svg.indexOf('<svg'));
    }
    return config;
}

export function outputDirectory(value: string | undefined, project: string): string {
    if (!value) throw new Error('Custom brand builds require --outdir');
    const out = resolve(value);
    const rel = relative(out, project);
    if (!rel || (!rel.startsWith('..') && !isAbsolute(rel))) throw new Error('Output must not contain the source project');
    const sourcePath = relative(project, out).split(/[\\/]/)[0];
    if (['src', 'tests', 'scripts', 'site', 'docs', 'skills', 'bin', '.agents', '.git'].includes(sourcePath)) throw new Error('Output would overwrite source files');
    if (out.includes('/.git/') || out.endsWith('/.git') || out === resolve(project, 'src')) throw new Error('Unsafe output directory');
    return out;
}

export function prepareOutput(directory: string): void {
    const marker = resolve(directory, '.brand-output');
    if (existsSync(directory) && readdirSync(directory).length && !existsSync(marker)) throw new Error('Refusing to replace a nonempty unmanaged output directory');
    rmSync(directory, { recursive: true, force: true });
    mkdirSync(directory, { recursive: true });
    writeFileSync(marker, 'Generated by the CLI build; safe to regenerate.\n');
}

/** Product documentation only: callers never pass runtime user/API data here. */
export function brandDocument(text: string, brand?: ResolvedBrand, file = 'README.md'): string {
    if (!brand) return text;
    if (!brand.repository) {
        // Source-only files are absent from the published package and static site.
        const sourceOnly = (href: string) => {
            const target = href.replace(/^https:\/\/(?:github\.com\/easysoft\/zentao-cli\/(?:blob|raw)\/[^/]+\/|raw\.githubusercontent\.com\/easysoft\/zentao-cli\/[^/]+\/)/, '');
            const path = target !== href ? target : posix.normalize(posix.join(posix.dirname(file), target));
            return /^(?:connectors|src|scripts|tests|site|\.agents)\/|^(?:AGENTS\.md|bun\.lock)(?:#|$)/.test(path);
        };
        text = text.replace(/\[([^\]]+)\]\(([^\s)]+)\)/g, (link, label, href) => sourceOnly(href) ? label : link);
        text = text.replace(/<a\b[^>]*href=["']([^"']+)["'][^>]*>([\s\S]*?)<\/a\s*>/g, (link, href, label) => sourceOnly(href) ? label : link);
    }
    // Existing links to upstream documents become relative before their names change.
    text = text.replace(/https:\/\/(?:github\.com\/easysoft\/zentao-cli\/(?:blob|raw)\/[^/]+\/|raw\.githubusercontent\.com\/easysoft\/zentao-cli\/[^/]+\/)([^\s"'<>`)]+)/g,
        (_, target: string) => relative(dirname(file), target.split('#')[0]).split('\\').join('/') + (target.includes('#') ? '#' + target.split('#').slice(1).join('#') : ''));
    if (!brand.repository) {
        text = text.replace(/<a\b[^>]*href=["']https:\/\/github\.com\/easysoft\/zentao-cli[^"']*["'][^>]*>[\s\S]*?<\/a\s*>/g, '');
        text = text.replace(/\[([^\]]+)\]\(https:\/\/github\.com\/easysoft\/zentao-cli(?:[^)]*)\)/g, '$1');
        text = text.replace(/^.*git clone .*easysoft\/zentao-cli.*\n/gm, '');
        text = text.replace(/^\s*repository: https:\/\/github\.com\/easysoft\/zentao-cli[^\n]*\n/gm, '');
        text = text.replace(/https:\/\/github\.com\/easysoft\/zentao-cli(?:\.git|\/issues|\/releases)?(?=[\s"'<>`)]|$)/g, brand.homepage);
    } else text = text.replace(/https:\/\/github\.com\/easysoft\/zentao-cli(?:\.git)?/g, brand.repository);
    text = text.replace(/https:\/\/www\.zentao\.net\/[^\s"'<>`)]*/g, brand.homepage);
    // SDK API identifiers must still refer to real exports.
    const saved: string[] = [];
    text = text.replace(/https:\/\/github\.com\/easysoft\/zentao-(?:api|skills)[^\s"'<>`)]*|\b(?:ZentaoClient|ZentaoError|getZentaoConfig|E_[A-Z_]*ZENTAO[A-Z_]*)\b/g, value => `\u0001${saved.push(value)-1}\u0001`);
    text = formatBrandText(text, brand).replace(/\u0001(\d+)\u0001/g, (_, index) => saved[Number(index)]);
    // GitHub/Vite heading slugs lowercase Latin words after the visible title is branded.
    text = text.replace(/(\]\([^\s)]*#)([^)]+)(\))/g, (_, prefix, hash, suffix) => prefix + hash.replaceAll(brand.displayName, brand.displayName.toLowerCase()) + suffix);
    return text.replace(/^[\t ]+$/gm, '');
}
